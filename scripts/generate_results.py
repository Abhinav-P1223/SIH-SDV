"""Generate docs/STAGE1_RESULTS.md from ACTUAL simulation runs.

Nothing in the results document is typed by hand: every number comes from
running the closed loop right now, on this machine, with the committed
configuration. Re-run after any change to keep the document honest.

    python scripts/generate_results.py
"""
from __future__ import annotations

import math
import platform
import subprocess
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402

from autonomy.core.config import AutonomyConfig, ObjectProfiles, load_vehicle_parameters, load_yaml  # noqa: E402
from autonomy.telemetry.telemetry import InMemorySink, TelemetryPublisher  # noqa: E402
from simulation.runner import Simulation, run_scenario  # noqa: E402
from simulation.scenarios.loader import SCENARIO_DIR, build_scenario  # noqa: E402


def fmt(v, nd=2):
    if v is None:
        return "n/a"
    if isinstance(v, float):
        if math.isinf(v):
            return "inf"
        return f"{v:.{nd}f}"
    return str(v)


def state_timeline(frames):
    """[(t_enter, state, reason)] from planning frames."""
    out = []
    last = None
    for f in frames:
        if not f.planning_cycle or f.decision is None:
            continue
        s = f.decision.state.value
        if s != last:
            out.append((f.timestamp, s, f.decision.reason))
            last = s
    return out


def cost_breakdown_example(frames):
    """Pick the planning frame with the most rejected candidates; show ranked feasible candidates."""
    plans = [f for f in frames if f.planning_cycle and f.plan is not None and f.plan.rejected_count > 0]
    if not plans:
        return None, None
    f = max(plans, key=lambda fr: (fr.plan.rejection_histogram.get("PREDICTED_COLLISION", 0), fr.plan.rejected_count))
    feas = sorted([c for c in f.plan.candidates if c.feasible], key=lambda c: c.total_cost)
    rej = [c for c in f.plan.candidates if not c.feasible]
    return f, (feas[:4], rej[:3])


def metrics_table(m, cfg):
    rows = [
        ("Scenario completed", m.scenario_completed),
        ("Termination reason", m.termination_reason),
        ("Collisions", m.collision_count),
        ("Minimum obstacle clearance [m]", fmt(m.minimum_obstacle_clearance)),
        (f"  (configured safety margin = {cfg.planning.safety_margin_m} m)", ""),
        ("Minimum TTC (route view) [s]", fmt(m.minimum_ttc)),
        ("Time to completion [s]", fmt(m.time_to_completion)),
        ("Path length [m]", fmt(m.path_length)),
        ("Average speed [m/s]", fmt(m.average_speed)),
        ("Max acceleration [m/s^2]", fmt(m.max_acceleration)),
        ("Max deceleration [m/s^2]", fmt(m.max_deceleration)),
        ("Max steering rate [rad/s]", fmt(m.max_steering_rate, 3)),
        ("Max curvature (driven) [1/m]", fmt(m.max_curvature, 4)),
        ("Mean |curvature| [1/m]", fmt(m.mean_abs_curvature, 4)),
        ("Replanning cycles", m.replanning_count),
        ("Plan changes (offset or speed target)", m.plan_change_count),
        ("Planner latency mean / max [ms]", f"{fmt(m.planning_latency_mean_ms, 1)} / {fmt(m.planning_latency_max_ms, 1)}"),
        ("Emergency-brake activations", m.emergency_brake_activations),
        ("Behaviour transitions", m.behavior_transitions),
        ("Behaviour state durations [s]", ", ".join(f"{k} {v:.1f}" for k, v in m.behavior_state_durations.items())),
        ("Max jerk [m/s^3] (hook)", fmt(m.max_jerk, 1)),
        ("Path smoothness, mean d(kappa)^2 (hook)", fmt(m.path_smoothness, 8) if m.path_smoothness is not None else "n/a"),
        ("Prediction error @1 s [m] (hook)", fmt(m.prediction_error_m, 3)),
        ("Perception latency (hook)", "n/a (no sensors in Stage 1)"),
    ]
    lines = ["| Metric | Value |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in rows]
    return "\n".join(lines)


def run_variant(name, override):
    """Run a scenario YAML with a modified agent parameter, without logs."""
    data = load_yaml(SCENARIO_DIR / f"{name.lower()}.yaml")
    for a in data["agents"]:
        a["params"].update(override)
    sc = build_scenario(data)
    mem = InMemorySink()
    sim = Simulation(sc, AutonomyConfig.load(), load_vehicle_parameters(), ObjectProfiles.load(),
                     TelemetryPublisher([mem]))
    return sim.run(), mem.frames


def main() -> int:
    cfg = AutonomyConfig.load()
    params = load_vehicle_parameters()
    out = []
    out.append("# Stage 1 Results — measured, not typed\n")
    out.append(f"Generated by `scripts/generate_results.py` on {datetime.now():%Y-%m-%d %H:%M} "
               f"({platform.system()} {platform.release()}, Python {platform.python_version()}, "
               f"numpy {np.__version__}).\n")
    out.append("Every number below is produced by running the closed loop with the committed configuration "
               "(`config/*.yaml`). Re-run the script after any change; do not edit the numbers by hand.\n")

    # tests
    try:
        r2 = subprocess.run([sys.executable, "-m", "pytest", "tests", "-p", "no:cacheprovider", "-q", "-o", "addopts="],
                            capture_output=True, text=True, cwd=ROOT)
        summary = [line for line in r2.stdout.splitlines() if "passed" in line or "failed" in line]
        out.append("## Automated tests\n")
        out.append(f"`python -m pytest tests` -> `{summary[-1].strip() if summary else r2.stdout[-200:]}`\n")
    except Exception as exc:  # pragma: no cover
        out.append(f"## Automated tests\n\nCould not run pytest: {exc}\n")

    # scenarios
    for name, img in (("SUDDEN_CATTLE_CROSSING", ["cattle_caution_t3.3.png", "cattle_avoid_t6.7.png"]),
                      ("SUDDEN_PEDESTRIAN_DART", ["pedestrian_emergency_t3.7.png"])):
        res = run_scenario(name, log_dir="logs", console=False, keep_frames=True)
        m = res.metrics
        ok = m.scenario_completed and m.collision_count == 0 and m.minimum_obstacle_clearance >= cfg.planning.safety_margin_m
        out.append(f"## {name} — {'PASS' if ok else 'FAIL'}\n")
        sc_data = load_yaml(SCENARIO_DIR / f"{name.lower()}.yaml")
        out.append(sc_data.get("description", "") + "\n")
        ag = sc_data["agents"][0]
        out.append(f"Agent `{ag['id']}` ({ag['type']}, behaviour {ag['behavior']}): "
                   + ", ".join(f"{k}={v}" for k, v in ag["params"].items()) + ". "
                   f"Ego desired speed {sc_data['ego']['desired_speed_mps']} m/s, "
                   f"desired lateral offset {sc_data['ego'].get('desired_lateral_offset_m', 0)} m, "
                   f"lane markings: {sc_data['road'].get('lane_markings', 'NONE')}.\n")
        out.append(metrics_table(m, cfg) + "\n")

        out.append("### Behaviour timeline (from the decision log)\n")
        out.append("| t [s] | state | machine-readable reason |\n|---|---|---|")
        for t, s, reason in state_timeline(res.frames):
            out.append(f"| {t:.2f} | {s} | {reason} |")
        out.append("")

        f, ex = cost_breakdown_example(res.frames)
        if f is not None:
            feas, rej = ex
            out.append(f"### Why was this trajectory selected? (planning cycle at t = {f.timestamp:.2f} s, "
                       f"{f.plan.feasible_count} feasible / {f.plan.rejected_count} rejected, "
                       f"{f.plan.latency_ms:.1f} ms)\n")
            keys = list(feas[0].weighted_costs) if feas else []
            out.append("| candidate | " + " | ".join(keys) + " | total |")
            out.append("|---|" + "---|" * (len(keys) + 1))
            for c in feas:
                mark = " **(selected)**" if c.id == f.plan.selected.id else ""
                out.append(f"| {c.id}{mark} | " + " | ".join(f"{c.weighted_costs[k]:.2f}" for k in keys)
                           + f" | {c.total_cost:.3f} |")
            out.append("")
            out.append("Rejected before ranking (examples):\n")
            for c in rej:
                out.append(f"- `{c.id}`: {c.rejection_reason.value} — {c.rejection_detail}")
            out.append("")
        out.append("### Engineering view snapshots\n")
        for i in img:
            out.append(f"![{i}](img/{i})\n")
        out.append(f"Telemetry: `logs/{name.lower()}.jsonl` (every step), `logs/{name.lower()}_summary.csv` (per planning cycle).\n")

    # negative finding: unavoidable dart
    out.append("## Negative result kept on record: pedestrian dart at 14 m\n")
    m14, fr14 = run_variant("SUDDEN_PEDESTRIAN_DART", {"trigger_distance_m": 14.0})
    v0 = 10.0
    d_brake = v0 ** 2 / (2 * params.max_deceleration)
    eb_t = next((f.timestamp for f in fr14 if f.safety.override_active), None)
    out.append(f"With the dart triggered at 14 m instead of 22 m the run ends with "
               f"`{m14.termination_reason}` (collisions = {m14.collision_count}, "
               f"min clearance = {fmt(m14.minimum_obstacle_clearance)} m, emergency-brake activations = "
               f"{m14.emergency_brake_activations}, override at t = {fmt(eb_t)} s). "
               f"Braking distance from {v0:.0f} m/s at {params.max_deceleration:.0f} m/s^2 is "
               f"{d_brake:.1f} m, and the constant-velocity predictor cannot see the dart until the pedestrian "
               f"has actually accelerated, so the outcome is physically determined, not a tuning problem. "
               f"It is recorded here rather than hidden; Stage 2 prediction (intent / acceleration-aware) is the lever.\n")

    # known limitations
    out.append("## Known limitations (Stage 1)\n")
    out.append("- Constant-velocity prediction lags accelerating agents (see the 14 m result above).\n"
               "- Jerk is not constrained: the planner may switch between deceleration and acceleration "
               "candidates between cycles; `max_jerk` is reported as a Stage 2 hook.\n"
               "- The reference direction is a polyline; candidate curvature assumes zero reference curvature "
               "per segment, adequate for the straight corridors used here.\n"
               "- Ground-truth objects with zero covariance; Stage 2 fusion will supply real covariances "
               "through the same `ObjectState` contract.\n"
               "- Planner latency (~40 ms mean in pure Python/numpy) is measured and logged, not real-time.\n")

    (ROOT / "docs" / "STAGE1_RESULTS.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote docs/STAGE1_RESULTS.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
